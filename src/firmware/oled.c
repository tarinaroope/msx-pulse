/* Send up to 22 command bytes in one I2C transaction. Control byte 0x00 marks
 * the payload as a command stream. */
static void oled_cmdn(const uint8_t *cmds, int n) {
    uint8_t buf[32];
    if (n > (int)(sizeof(buf) - 1)) return;
    buf[0] = 0x00;
    memcpy(buf + 1, cmds, (size_t)n);
    i2c_write_blocking(i2c0, oled_addr, buf, (size_t)(n + 1), false);
}

static void oled_flush(void) {
    /* Horizontal addressing, window = full display. */
    static const uint8_t addr_setup[] = { 0x21, 0, 127, 0x22, 0, 7 };
    oled_cmdn(addr_setup, sizeof(addr_setup));

    /* One data burst per page: [0x40, 128 bytes]. */
    uint8_t buf[OLED_W + 1];
    buf[0] = 0x40;
    for (int pg = 0; pg < OLED_PAGES; pg++) {
        memcpy(buf + 1, fb[pg], OLED_W);
        i2c_write_blocking(i2c0, oled_addr, buf, sizeof(buf), false);
    }
}

static void oled_ssd1306_init(void) {
    static const uint8_t seq[] = {
        0xAE,        /* display off                          */
        0xD5, 0x80,  /* clock divide ratio / oscillator freq */
        0xA8, 0x3F,  /* multiplex ratio: 64 rows - 1         */
        0xD3, 0x00,  /* display offset: 0                    */
        0x40,        /* display start line: 0                */
        0x8D, 0x14,  /* charge pump: enable                  */
        0x20, 0x00,  /* memory addressing: horizontal        */
        0xA1,        /* segment re-map (column 127 = SEG0)   */
        0xC8,        /* COM scan: remapped (top → bottom)    */
        0xDA, 0x12,  /* COM pins HW config: alt, no remap    */
        0x81, 0xCF,  /* contrast: 0xCF                       */
        0xD9, 0xF1,  /* pre-charge period                    */
        0xDB, 0x40,  /* VCOMH deselect level                 */
        0xA4,        /* output follows RAM (not all-on)      */
        0xA6,        /* normal polarity (not inverted)       */
        0xAF,        /* display on                           */
    };
    oled_cmdn(seq, sizeof(seq));
}

